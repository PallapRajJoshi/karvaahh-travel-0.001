// data/europe/countries.ts
// CMS-ready country data for /packages/international/europe.
//
// - `operationalStatus`: "active" is bookable; "limited" shows an advisory and
//   offers enquiries only; "inactive" stays listed with an advisory and no booking
//   CTA, and is left out of filters, counts and the trip builder.
// - `href` is the country's future page. It is linked only once the route is in
//   LIVE_ROUTES (lib/europe/config.ts), so no broken links are rendered.
// - `transcontinental` marks destinations that span Europe and Asia, or are
//   commonly sold with European trips. The UI labels them so the page never
//   implies they are wholly European.
// - Package counts are derived from packages.ts, never typed in here.
// - `schengen` / `eu` / `currency` drive the Travel Essentials and Currency
//   sections. Verify them when membership changes.

import { img, type EuropeImage } from "./images";
import type { EuropeRegionId } from "./regions";
import type { SeasonId } from "./seasons";
import type { EuropeStyleId } from "./travel-styles";

export type OperationalStatus = "active" | "limited" | "inactive";

export interface EuropeCountry {
  id: string;
  name: string;
  slug: string;
  /** ISO 3166-1 alpha-2 code (lower case), used for the flag and the map. */
  iso: string;
  /** Directory group. */
  region: EuropeRegionId;
  /** Extra filter tags, e.g. "scandinavia", "mediterranean", "balkans". */
  regions?: EuropeRegionId[];
  image?: EuropeImage;
  description: string;
  /** Cities and destinations, most important first. */
  cities: string[];
  experiences: string[];
  travelStyles: EuropeStyleId[];
  bestSeasons: SeasonId[];
  bestTime?: string;
  /** 1–5. Orders cards within a region. */
  popularity: number;
  featured?: boolean;
  transcontinental?: boolean;
  operationalStatus: OperationalStatus;
  /** Shown on the card and map. Required when status is not "active". */
  advisory?: string;
  currency: { code: string; name: string };
  schengen: boolean;
  eu: boolean;
  /** [latitude, longitude] for the map marker. */
  coords: [number, number];
  href: string;
}

