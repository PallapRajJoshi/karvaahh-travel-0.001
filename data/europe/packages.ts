// data/europe/packages.ts
// CMS-ready Europe package templates. One list powers the package carousel, the
// multi-country circuits, the travel-style filters and the package counts on
// country cards and the map.
//
// - `price` stays undefined until Karvaahh publishes a real price. The UI then
//   shows "Price on Request"; prices are never invented.
// - Only `active: true` packages are rendered anywhere.
// - `href` is the future package URL; it is linked only once the route is in
//   LIVE_ROUTES (lib/europe/config.ts). Until then cards offer an enquiry.
// - `circuit: true` features the package in "One Trip. Multiple Countries.",
//   where `route` stops (city names) are drawn on the map using `routeCoords`.
// - `duration` is a suggested length and is fully customisable.

import { img, type EuropeImage } from "./images";
import type { SeasonId } from "./seasons";
import type { EuropeStyleId } from "./travel-styles";

export type PackageType = "private" | "group" | "fixed-departure" | "tailor-made";

export interface EuropePackage {
  id: string;
  title: string;
  slug: string;
  /** Country ids in travel order. Empty for the fully customized template. */
  countries: string[];
  /** Stops for the route line. */
  destinations: string[];
  /** Display duration, e.g. "7N/8D". */
  duration: string;
  /** Nights, for sorting. */
  nights: number;
  travelStyles: EuropeStyleId[];
  season?: SeasonId[];
  packageType: PackageType[];
  image?: EuropeImage;
  description: string;
  /** Starting price per person in INR. Leave undefined unless published. */
  price?: number;
  active: boolean;
  featured?: boolean;
  circuit?: boolean;
  /** The "build your own" template: always shown, never filtered out. */
  custom?: boolean;
  /** [lat, lon] per stop, for the circuit map. Only needed when `circuit` is true. */
  routeCoords?: [number, number][];
  href: string;
}

