// data/asia-destinations.ts
// CMS-ready destination data for /packages/international/asia.
//
// - Set `active: false` to hide a destination everywhere on the page.
// - `href` is the destination's future URL. It is only linked once the route is
//   listed in LIVE_ROUTES (lib/asia/config.ts), so no broken links are rendered.
// - `image` is optional. Destinations without a verified photo render a designed
//   gradient + flag fallback instead of an unrelated stock image.
// - Package counts are derived from data/asia-packages.ts, never typed in here.

import type { AsiaRegionId } from "./asia-regions";
import type { TravelStyleId } from "./travel-styles";

export type BudgetLevel = "budget" | "mid-range" | "premium" | "luxury";

export interface AsiaImage {
  src: string;
  alt: string;
}

export interface AsiaDestination {
  id: string;
  country: string;
  slug: string;
  region: AsiaRegionId;
  /** ISO 3166-1 alpha-2 code, used for the flag. */
  iso: string;
  image?: AsiaImage;
  description: string;
  /** Cities, regions or focus areas. */
  cities: string[];
  experiences: string[];
  travelStyles: TravelStyleId[];
  /** Typical trip length in days, [min, max]. Drives the duration filter. */
  days: [number, number];
  bestTime?: string;
  budgetLevel?: BudgetLevel;
  /** 1–5. Used to order cards within a region. */
  popularity: number;
  featured?: boolean;
  active: boolean;
  href: string;
  /** [latitude, longitude] for the map marker. */
  coords: [number, number];
  /** Availability caveat shown on the card and map. */
  note?: string;
}

